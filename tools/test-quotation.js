const assert = require('node:assert/strict');
const fs = require('node:fs');
const Q = require('../public/lib/quotation.js');
const seed = JSON.parse(fs.readFileSync(require('node:path').join(__dirname, '../public/data/seed.js'), 'utf8').replace(/^window\.SEED=/, '').trim().replace(/;$/, ''));
const hn = seed.vendors.find(v => v.name === 'Hansinok');
const base = Q.rows(hn).map(r => ({ ...r, ...(seed.quotationDefaults.Hansinok.items[r.id] || {}) }));
assert.equal(Q.total(base).amount, 30025);
const draft = structuredClone(base);
draft.find(r => r.id === 'item3').qty += 60;
draft.find(r => r.id === 'item4').qty += 10;
draft.find(r => r.id === 'pages').qty = 5;
assert.equal(Q.summary(base, draft, hn.price).delta, null, 'Missing page rate must prevent a complete budget');
draft.find(r => r.id === 'pages').rate = 100;
assert.equal(Q.summary(base, draft, hn.price).delta, 3850);
assert.equal(Q.total(draft).amount, 33875);
draft.find(r => r.id === 'item0').qty = 0;
assert.equal(Q.summary(base, draft, hn.price).delta, -1350);
const wm = Q.rows(seed.vendors.find(v => v.name === 'Willmore'));
assert.equal(wm.find(r => r.label === 'Multimedia').qty, 300);
assert.equal(Q.round(wm.find(r => r.label === 'Multimedia').rate * 300), 3237.5);
assert.equal(Q.total([{ qty: 0, rate: null }]).missing, 0);
assert.equal(Q.total([{ qty: 1, rate: null }]).missing, 1);
for (const bad of [-1, Infinity, NaN, '5']) assert.equal(Q.valid(bad), false);
assert.equal(hn.price, 30025, 'Planner must not mutate the quotation');
console.log('PASS: formal baseline, seconds conversion, additions/reductions, missing rates, zero quantities, invalid input, and immutable source.');
